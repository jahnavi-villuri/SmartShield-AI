"""Write one model card per saved model into docs/model_cards/.

    python -m scripts.make_model_cards

Every number comes from the model's metadata.json, so a card cannot disagree with the model file.
The narrative parts (intended use, ethics) are written here once. tests/test_docs.py fails when a
committed card differs from what this script would write: retrain, then rerun this script.
"""

import json
from pathlib import Path

from config import settings

OUT = settings.PROJECT_ROOT / "docs" / "model_cards"

METRIC_COLUMNS = (
    ("precision", "Precision"),
    ("recall", "Recall"),
    ("f1", "F1"),
    ("false_positive_rate", "False-alarm rate"),
    ("pr_auc", "PR-AUC"),
)


def _f(value, pct: bool = False) -> str:
    if value is None:
        return "-"
    return f"{value:.1%}" if pct else f"{value:.3f}"


def metrics_table(rows: list[tuple[str, dict]]) -> str:
    head = "| Evaluation set | n | " + " | ".join(label for _, label in METRIC_COLUMNS) + " |"
    sep = "|---|---:|" + "---:|" * len(METRIC_COLUMNS)
    lines = [head, sep]
    for name, d in rows:
        cells = [_f(d.get(key)) for key, _ in METRIC_COLUMNS]
        lines.append(f"| {name} | {d.get('n', '-')} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _details(meta: dict, extra: list[tuple[str, str]]) -> str:
    rows = [
        ("Algorithm", f"`{meta['model']}` (scikit-learn {meta.get('scikit_learn', '?')})"),
        ("Trained", str(meta["created_utc"])[:10]),
        ("Python", str(meta.get("python", "?"))),
        (
            "Model file",
            f"{meta.get('model_file_mb', '?')} MB, SHA-256 `{meta['model_sha256'][:16]}...`",
        ),
        ("Training seed", str(meta.get("seed", "?"))),
        *extra,
    ]
    return "\n".join(f"| {k} | {v} |" for k, v in rows)


def _sizes(meta: dict) -> str:
    d = meta["data_sizes"]
    return ", ".join(f"{k} {v:,}" for k, v in d.items() if isinstance(v, int))


def _limits(meta: dict) -> str:
    return "\n".join(f"- {item}" for item in meta.get("limitations", []))


def _card(
    title: str,
    meta: dict,
    purpose: str,
    out_of_scope: str,
    data: str,
    table: str,
    reading: str,
    ethics: str,
    extra_details: list[tuple[str, str]],
    code: str,
) -> str:
    return f"""# Model card: {title}

> Generated by `python -m scripts.make_model_cards` from `models/{code}/metadata.json`. Do not edit by hand.

## Model details
| | |
|---|---|
{_details(meta, extra_details)}

## Intended use
{purpose}

**Out of scope:** {out_of_scope}

## Training data
{data}

Sizes: {_sizes(meta)}. Details: `docs/dataset_cards/`.

## Evaluation
{table}

{reading}

## Known limitations
{_limits(meta)}

## Ethical considerations
{ethics}

## Using the model
```python
from src.detection.{{module}} import {{loader}}

detector = {{loader}}()  # verifies the SHA-256 checksum before loading
```
See `app.py` for a complete example. Predictions are scores with a threshold chosen on validation data, not probabilities for your inbox.
"""


def sms_card(meta: dict, type_meta: dict | None) -> str:
    m = meta["metrics"]
    rows = [
        ("Validation", m["validation"]),
        ("Test (same sources as training)", m["test"]),
        ("External: Indian telecom SMS", m["external_india"]),
        ("Hand-written bank/transaction alerts", m["challenge_transactional"]),
    ]
    table = metrics_table(rows)
    private = m.get("private_heldout")
    reading = (
        f"Threshold {meta['threshold']:.2f} chosen on validation data ({meta['threshold_rule']}). "
        "The external set comes from a different region and period; its drop is the honest "
        "estimate of how the model behaves on messages unlike its training data. The spam share "
        "in training and test data (38%) is far higher than in a real phone, so real-world "
        "precision will be lower than shown."
    )
    if private:
        reading += (
            f" On the owner's own held-out messages, {private['legit_flagged']} of "
            f"{private['legit']} legitimate messages were wrongly flagged ({private['n']} in total)."
        )
    if type_meta:
        cv = type_meta["metrics"]["cross_validated_dev"]
        reading += (
            f"\n\n**Second stage (promotional vs scam):** `{type_meta['model']}` trained on "
            f"{type_meta['data_sizes']['dev']} hand-labelled messages "
            f"({type_meta['data_sizes']['dev_scam']} scams). Cross-validated: precision "
            f"{cv['precision']:.2f}, recall {cv['recall']:.2f}, accuracy {cv['accuracy']:.2f}. "
            "Its labels were produced by one AI labeller and are not human-verified."
        )
    return (
        _card(
            "SMS: ordinary, promotional or scam",
            meta,
            "Show a learner how a text classifier flags unwanted SMS (promotional or scam) and which "
            "words drove the score. Two stages: a main model separates ordinary from unwanted "
            "messages, then a small second model separates promotional from scam.",
            "Blocking, deleting or reporting messages automatically; judging non-English messages; "
            "any decision about a person; replacing a carrier's spam filter.",
            "UCI SMS Spam Collection, Mendeley SMS Phishing Dataset, ScamShield `Smishing_Dataset` "
            "(English, non-synthetic rows), 3,000 template-written bank/transaction messages, and the "
            "owner's own real messages (hash-split, never evaluated on training rows).",
            table,
            reading,
            "A bank alert wrongly marked as scam can hide something a person needs to see, which is "
            "why the threshold favours precision. The data over-represents UK/US and Indian text and "
            "formal bank wording; messages in other languages or styles are treated unreliably. The "
            "app never says a message is 'safe'.",
            [("Threshold", f"{meta['threshold']:.2f}"), ("Features", meta.get("features", "?"))],
            "sms_spam",
        )
        .replace("{module}", "spam_detector")
        .replace("{loader}", "load_sms_detector")
    )


def email_card(meta: dict) -> str:
    m = meta["metrics"]
    ext = meta["external_2026"]
    ch = m["challenge_modern"]
    rows = [
        ("Validation", m["validation"]),
        ("Test (Enron-era)", m["test"]),
        ("Hand-written modern emails (24 legitimate, 10 spam)", ch),
    ]
    table = metrics_table(rows)
    syn = m.get("synthetic_heldout")
    reading = (
        f"**Real 2026 spam** ({ext['n']:,} emails, June to October 2026): {ext['detection_rate']:.1%} "
        "detected. This set contains no legitimate email, so it measures detection only, never false "
        f"alarms. On the 24 hand-written modern legitimate emails the model flags {ch['fp']} "
        f"({ch['fp'] / (ch['fp'] + ch['tn']):.0%}). The near-perfect Enron-era test score mostly "
        "reflects recognising 'Enron staff email versus everything else'."
    )
    if syn:
        reading += (
            f" On the held-out half of a small synthetic modern dataset, {syn['legit_flagged']} of "
            f"{syn['legit']} legitimate emails were flagged and {syn['spam_caught']} of {syn['spam']} "
            "phishing emails were caught."
        )
    return (
        _card(
            "Email: spam and phishing",
            meta,
            "Teach why a high test score can be misleading, and flag email text that looks like spam "
            "or phishing with the terms behind the score.",
            "Filtering a real mailbox; judging attachments, images, headers or senders; non-English "
            "email; any decision about a person.",
            "Enron-Spam (ham: Enron staff email 1999 to 2002; spam: 2001 to 2005), plus 100 synthetic "
            "modern emails (darkknight25, MIT) trained at low weight and the owner's own emails if "
            "present. Words that merely identify the Enron source are masked.",
            table,
            reading,
            "Wrongly hiding a legitimate email costs more than letting spam through, so the threshold "
            "targets high precision. The model treats ordinary modern automated mail (statements, "
            "verification codes, receipts) as suspicious about a quarter of the time. The Email tab "
            "shows this as a standing warning. Links in emails are never opened.",
            [
                ("Threshold", f"{meta['threshold']:.3f}"),
                ("Features", meta.get("features", "?")),
                (
                    "Guard on modern legitimate email",
                    "passed" if meta.get("guard_passed") else "failed",
                ),
            ],
            "email_spam",
        )
        .replace("{module}", "email_detector")
        .replace("{loader}", "load_email_detector")
    )


def comments_card(meta: dict) -> str:
    m = meta["metrics"]
    rows = [
        (
            "Validation (macro)",
            {
                **m["validation"]["summary"],
                "precision": m["validation"]["summary"].get("micro_precision"),
                "recall": m["validation"]["summary"].get("micro_recall"),
                "f1": m["validation"]["summary"].get("macro_f1"),
                "pr_auc": m["validation"]["summary"].get("macro_pr_auc"),
            },
        ),
        (
            "Official test (macro)",
            {
                **m["official_test"]["summary"],
                "precision": m["official_test"]["summary"].get("micro_precision"),
                "recall": m["official_test"]["summary"].get("micro_recall"),
                "f1": m["official_test"]["summary"].get("macro_f1"),
                "pr_auc": m["official_test"]["summary"].get("macro_pr_auc"),
            },
        ),
    ]
    per = m["official_test"]["per_label"]
    label_rows = "\n".join(
        f"| {k} | {v['positives']:,} | {v['precision']:.3f} | {v['recall']:.3f} | {v['f1']:.3f} |"
        for k, v in per.items()
    )
    bias = meta["bias_probe"]
    ctx = meta["context_probe"]
    table = (
        metrics_table(rows)
        + "\n\nRows show micro precision and recall with macro F1 and macro PR-AUC.\n\n"
        "**Official test set, per label**\n\n| Label | Positive examples | Precision | Recall | F1 |\n"
        "|---|---:|---:|---:|---:|\n" + label_rows
    )
    reading = (
        f"Each label has its own threshold. Rare labels (threat, severe_toxic, identity_hate) are "
        f"weaker. **Bias probe:** neutral sentences such as 'I am a ... person' were flagged up to "
        f"{bias['max_flagged_share']:.0%} of the time for the worst identity term "
        f"('{bias['worst_term']}'). **Context probe:** {ctx['benign_flagged']} of {ctx['benign_n']} "
        "benign sentences that merely mention or negate toxic words were flagged."
    )
    return (
        _card(
            "Comments: six kinds of toxicity",
            meta,
            "Show multi-label classification and per-label thresholds, and prompt a human moderator to "
            "look at a comment, with the words behind each score.",
            "Automatic moderation, banning, ranking or reporting people; judging non-English text; "
            "anything where a false flag harms someone. Not suitable as the only moderation signal.",
            "Jigsaw Toxic Comment Classification (Wikipedia talk-page comments, about 2017; crowd "
            "labels). A round of synthetic neutral identity sentences was tried to reduce bias; a "
            "later round was rejected because it did not help.",
            table,
            reading,
            "This is the highest-risk model in the project. It can mistake the mention of an identity "
            "(for example 'gay', 'black') for toxicity and cannot read negation, quotes or sarcasm. "
            "Using it to moderate people automatically would harm exactly the groups it misjudges. "
            "The app shows the bias result as a warning on the Comments tab.",
            [("Features", "word and character TF-IDF"), ("Labels", ", ".join(meta["labels"]))],
            "toxicity",
        )
        .replace("{module}", "toxicity_detector")
        .replace("{loader}", "load_toxicity_detector")
    )


def url_card(meta: dict) -> str:
    m = meta["metrics"]
    ext = m["external"]
    rows = [
        ("Validation", m["validation"]),
        ("Newer URLs (temporal test)", m["test_temporal"]),
        ("Unseen domains", m["test_unseen_groups"]),
        ("Free-hosting platforms only", m["test_hosting_platforms"]),
        ("External: CompPhish", ext["compphish"]),
        ("External: PhishBench", ext["phishbench"]),
    ]
    table = metrics_table(rows)
    op = ext.get("openphish_2026-10-12", {})
    ch = m["challenge"]
    reading = (
        f"The temporal test uses URLs collected after the training period "
        f"({meta['date_ranges']['test']}). External collections were never trained on. A live "
        f"OpenPhish feed (2026-10-12, {op.get('n', '?')} URLs) was detected at "
        f"{op.get('detection_rate', 0):.1%}. On the hand-written set, {ch['legit_flagged']} of "
        f"{ch['legit_n']} ordinary links were wrongly flagged and {ch['phish_caught']} of "
        f"{ch['phish_n']} phishing-style links were caught."
    )
    return (
        _card(
            "URLs: potentially phishing",
            meta,
            "Show what can and cannot be learned from the text of an address alone, with the features "
            "behind the score. The address is never opened.",
            "Declaring a site safe; blocking sites; judging page content, certificates, domain age or "
            "reputation; shortened links (the app says 'Cannot judge').",
            "PhreshPhish (CC BY 4.0, 2024 to 2025) plus PhiUSIIL (legitimate homepages balance "
            "PhreshPhish's deep pages). Structural shortcuts found in the data (www, https, query "
            "string, empty path) were removed as features.",
            table,
            reading,
            "A false alarm can make a legitimate small site look dangerous. The model mistakes many "
            "legitimate pages on free hosting platforms for phishing because in the training data "
            "almost every address on those platforms was phishing. The app says 'Potentially "
            "phishing' or 'Likely legitimate', never 'safe'.",
            [
                ("Threshold", f"{meta['threshold']:.3f}"),
                ("Features", f"{len(meta['feature_names'])} numeric URL measurements"),
            ],
            "phishing",
        )
        .replace("{module}", "phishing_detector")
        .replace("{loader}", "load_phishing_detector")
    )


def build_cards(models_dir: Path | None = None) -> dict[str, str]:
    root = Path(models_dir) if models_dir is not None else settings.MODELS_DIR

    def load(folder: str) -> dict | None:
        path = root / folder / "metadata.json"
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    cards = {}
    sms, sms_type = load("sms_spam"), load("sms_type")
    if sms:
        cards["sms.md"] = sms_card(sms, sms_type)
    for name, folder, builder in (
        ("email.md", "email_spam", email_card),
        ("comments.md", "toxicity", comments_card),
        ("url.md", "phishing", url_card),
    ):
        meta = load(folder)
        if meta:
            cards[name] = builder(meta)

    rows = []
    for title, key, meta in (
        ("SMS", "sms.md", sms),
        ("Email", "email.md", load("email_spam")),
        ("Comments", "comments.md", load("toxicity")),
        ("URL", "url.md", load("phishing")),
    ):
        if meta:
            rows.append(
                f"| [{title}]({key}) | `{meta['model']}` | {str(meta['created_utc'])[:10]} | {_sizes(meta)} |"
            )
    cards["README.md"] = (
        "# Model cards\n\nOne card per detector, generated from each model's `metadata.json` "
        "(`python -m scripts.make_model_cards`). A model card says what a model is for, what it "
        "was trained and tested on, how well it did, and where it fails.\n\n"
        "| Detector | Algorithm | Trained | Data sizes |\n|---|---|---|---|\n"
        + "\n".join(rows)
        + "\n\nRead the 'Known limitations' and 'Ethical considerations' sections before using any score.\n"
    )
    return cards


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in build_cards().items():
        (OUT / name).write_text(text, encoding="utf-8", newline="\n")
        print("written", OUT / name)


if __name__ == "__main__":
    main()
